import mongoose, {
  type HydratedDocument,
  type Model,
  Schema,
  Types,
} from 'mongoose';

/**
 * External identity providers currently considered for Propix authentication.
 * Provider login flows and token handling are intentionally outside this Model.
 */
export const AUTHENTICATION_PROVIDERS = ['google', 'apple'] as const;

export type AuthenticationProvider =
  (typeof AUTHENTICATION_PROVIDERS)[number];

/**
 * A stable identity issued by an external identity provider.
 * Store the provider's subject/user identifier, never its access or ID tokens.
 */
export interface ExternalIdentity {
  provider: AuthenticationProvider;
  providerUserId: string;
  linkedAt: Date;
}

/**
 * Authentication-specific data for one Propix user.
 * The password is stored only as a one-way hash generated by the auth service.
 */
export interface UserAuthentication {
  userId: Types.ObjectId;
  passwordHash: string | null;
  passwordChangedAt: Date | null;
  externalIdentities: ExternalIdentity[];
  lastAuthenticatedAt: Date | null;
  createdAt?: Date;
  updatedAt?: Date;
}

export type UserAuthenticationDocument = HydratedDocument<UserAuthentication>;

const externalIdentitySchema = new Schema<ExternalIdentity>(
  {
    provider: {
      type: String,
      enum: {
        values: AUTHENTICATION_PROVIDERS,
        message: 'Unsupported authentication provider.',
      },
      required: [true, 'Authentication provider is required.'],
    },
    providerUserId: {
      type: String,
      required: [true, 'Provider user ID is required.'],
      trim: true,
      minlength: [1, 'Provider user ID cannot be empty.'],
      maxlength: [255, 'Provider user ID cannot exceed 255 characters.'],
    },
    linkedAt: {
      type: Date,
      default: Date.now,
      required: true,
    },
  },
  {
    _id: false,
    id: false,
    strict: 'throw',
  },
);

const userAuthenticationSchema = new Schema<
  UserAuthentication,
  Model<UserAuthentication>
>(
  {
    userId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User reference is required.'],
      immutable: true,
    },
    passwordHash: {
      type: String,
      default: null,
      select: false,
      minlength: [1, 'Password hash cannot be empty.'],
      maxlength: [512, 'Password hash cannot exceed 512 characters.'],
    },
    passwordChangedAt: {
      type: Date,
      default: null,
    },
    externalIdentities: {
      type: [externalIdentitySchema],
      default: [],
      validate: {
        validator: (identities: ExternalIdentity[]) => {
          const seen = new Set<string>();

          return identities.every((identity) => {
            const key = `${identity.provider}:${identity.providerUserId}`;

            if (seen.has(key)) {
              return false;
            }

            seen.add(key);
            return true;
          });
        },
        message: 'An external identity cannot be linked more than once.',
      },
    },
    lastAuthenticatedAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
    strict: 'throw',
    toJSON: {
      transform(_document, returnedObject: Record<string, unknown>) {
        delete returnedObject.passwordHash;
        return returnedObject;
      },
    },
    toObject: {
      transform(_document, returnedObject: Record<string, unknown>) {
        delete returnedObject.passwordHash;
        return returnedObject;
      },
    },
  },
);

// One authentication record per User. Credentials remain outside User itself.
userAuthenticationSchema.index(
  { userId: 1 },
  { unique: true, name: 'user_authentication_user_unique' },
);

// A provider identity can belong to only one Propix account.
// The partial filter excludes documents whose external identity list is empty.
userAuthenticationSchema.index(
  {
    'externalIdentities.provider': 1,
    'externalIdentities.providerUserId': 1,
  },
  {
    unique: true,
    name: 'user_authentication_external_identity_unique',
    partialFilterExpression: {
      'externalIdentities.provider': { $exists: true },
    },
  },
);

const UserAuthenticationModel =
  (mongoose.models.UserAuthentication as
    | Model<UserAuthentication>
    | undefined) ??
  mongoose.model<UserAuthentication>(
    'UserAuthentication',
    userAuthenticationSchema,
  );

export { externalIdentitySchema, userAuthenticationSchema };
export default UserAuthenticationModel;
